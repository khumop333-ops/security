/**
 * PostgreSQL storage driver (used on Vercel via Supabase Postgres).
 *
 * Mirrors db-sqlite.js exactly — same schema, same seed data, same function
 * signatures and return shapes — so the storage layer is interchangeable.
 * Timestamps remain ISO-8601 UTC strings; "booleans" remain 0/1 integers.
 *
 * Connection: DATABASE_URL (direct connection to Supabase, e.g.
 * postgres://user:pass@db.<ref>.supabase.co:5432/postgres).
 */
import postgres from 'postgres';
import { hashPin, verifyPin } from './pin.js';

export { hashPin, verifyPin };

/** Statuses that mean "responders are actively working this alert". */
export const ACTIVE_STATUSES = ['dispatch_notified', 'responder_en_route', 'responder_arrived'];

const sql = postgres(process.env.DATABASE_URL, {
  max: 5,
  idle_timeout: 20,
  connect_timeout: 10,
  ssl: 'require',
  // Safe with connection poolers (pgbouncer transaction mode).
  prepare: false
});

const nowIso = () => new Date().toISOString();
const daysAgoIso = (days, hour = 10, minute = 30) => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

/* ------------------------------------------------------------------ schema */

const SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS profile (
    id                    INTEGER PRIMARY KEY CHECK (id = 1),
    first_name            TEXT    NOT NULL DEFAULT '',
    surname               TEXT    NOT NULL DEFAULT '',
    id_number             TEXT    NOT NULL DEFAULT '',
    mobile                TEXT    NOT NULL DEFAULT '',
    address               TEXT    NOT NULL DEFAULT '',
    medical_conditions    TEXT    NOT NULL DEFAULT '',
    allergies             TEXT    NOT NULL DEFAULT '',
    contract_number       TEXT    NOT NULL DEFAULT '',
    pin_hash              TEXT    NOT NULL DEFAULT '',
    notify_sms            INTEGER NOT NULL DEFAULT 1,
    notify_whatsapp       INTEGER NOT NULL DEFAULT 0,
    notify_status_updates INTEGER NOT NULL DEFAULT 1,
    popia_consent         INTEGER NOT NULL DEFAULT 0,
    popia_consent_at      TEXT,
    updated_at            TEXT    NOT NULL DEFAULT ''
  );

  CREATE TABLE IF NOT EXISTS emergency_contacts (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL,
    phone        TEXT NOT NULL,
    relationship TEXT NOT NULL DEFAULT '',
    position     INTEGER NOT NULL DEFAULT 0
  );

  CREATE TABLE IF NOT EXISTS alerts (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            TEXT NOT NULL UNIQUE,
    type            TEXT NOT NULL CHECK (type IN ('panic', 'test')),
    status          TEXT NOT NULL,
    lat             DOUBLE PRECISION,
    lng             DOUBLE PRECISION,
    accuracy        DOUBLE PRECISION,
    address         TEXT NOT NULL DEFAULT '',
    address_source  TEXT NOT NULL DEFAULT 'gps',
    user_name       TEXT NOT NULL DEFAULT '',
    user_id_number  TEXT NOT NULL DEFAULT '',
    user_mobile     TEXT NOT NULL DEFAULT '',
    contract_number TEXT NOT NULL DEFAULT '',
    medical_summary TEXT NOT NULL DEFAULT '',
    eta_minutes     INTEGER,
    responder_name  TEXT NOT NULL DEFAULT '',
    responder_unit  TEXT NOT NULL DEFAULT '',
    cancel_reason   TEXT NOT NULL DEFAULT '',
    resolution_note TEXT NOT NULL DEFAULT '',
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS alert_events (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id    INTEGER NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
    from_status TEXT,
    to_status   TEXT NOT NULL,
    actor       TEXT NOT NULL CHECK (actor IN ('user', 'control_room', 'system')),
    actor_name  TEXT NOT NULL DEFAULT '',
    note        TEXT NOT NULL DEFAULT '',
    created_at  TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS data_requests (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_type TEXT NOT NULL,
    detail       TEXT NOT NULL DEFAULT '',
    created_at   TEXT NOT NULL
  );
`;

/** Schema + demo seed, created lazily on first query and memoised. */
let ready = null;
function init() {
  ready ??= (async () => {
    await sql.unsafe(SCHEMA_SQL);
    await seedIfEmpty();
  })();
  return ready;
}

