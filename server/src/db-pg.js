/** Replace the contact list atomically (max 3 contacts, per product spec). */
export async function replaceContacts(contacts) {
  await init();
  return sql.begin(async (tx) => {
    await tx.unsafe('DELETE FROM emergency_contacts');
    for (const [i, c] of contacts.slice(0, 3).entries()) {
      await tx.unsafe(
        'INSERT INTO emergency_contacts (name, phone, relationship, position) VALUES ($1, $2, $3, $4)',
        [c.name || '', c.phone || '', c.relationship || '', i + 1]
      );
    }
  }).then(listContacts);
}

