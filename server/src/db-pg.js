/**
 * Move an alert to a new status with optional dispatch metadata.
 * Returns the updated alert, or throws { statusCode, code, message }.
 */
export async function updateAlertStatus(id, {
  status, etaMinutes, responderName, responderUnit, note, operatorName, cancelReason, actor = 'control_room'
}) {
  await init();
  return sql.begin(async (tx) => {
    const rows = await tx.unsafe('SELECT * FROM alerts WHERE id = $1 FOR UPDATE', [id]);
    const alert = rows[0];
    if (!alert) {
      const err = new Error('Alert not found.');
      err.statusCode = 404;
      err.code = 'NOT_FOUND';
      throw err;
    }

    const allowedNext = {
      dispatch_notified: ['responder_en_route', 'resolved', 'cancelled'],
      responder_en_route: ['responder_arrived', 'resolved', 'cancelled'],
      responder_arrived: ['resolved', 'cancelled'],
      resolved: [],
      cancelled: [],
      test_complete: []
    };
    if (!allowedNext[alert.status]?.includes(status)) {
      const err = new Error(`Cannot move alert from "${alert.status}" to "${status}".`);
      err.statusCode = 409;
      err.code = 'INVALID_TRANSITION';
      throw err;
    }

    await tx.unsafe(
      `UPDATE alerts SET
         status = $1,
         eta_minutes = COALESCE($2, eta_minutes),
         responder_name = CASE WHEN $3 != '' THEN $3 ELSE responder_name END,
         responder_unit = CASE WHEN $4 != '' THEN $4 ELSE responder_unit END,
         cancel_reason = CASE WHEN $5 != '' THEN $5 ELSE cancel_reason END,
         resolution_note = CASE WHEN $6 != '' THEN $6 ELSE resolution_note END,
         updated_at = $7
       WHERE id = $8`,
      [
        status,
        etaMinutes ?? null,
        responderName || '',
        responderUnit || '',
        cancelReason || '',
        note || '',
        nowIso(), id
      ]
    );

    await tx.unsafe(
      `INSERT INTO alert_events (alert_id, from_status, to_status, actor, actor_name, note, created_at)
       VALUES ($1, $2, $3, $4, $5, $6, $7)`,
      [id, alert.status, status, actor,
       operatorName || (actor === 'user' ? 'Client' : 'Control room'), note || '', nowIso()]
    );

    const updated = await tx.unsafe('SELECT * FROM alerts WHERE id = $1', [id]);
    return updated[0];
  });
}

